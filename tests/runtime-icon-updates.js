import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import {ProviderIconUpdater} from '../providerIconUpdates.js';
import {resolveProviderIcon, providerIconVersion, bundledProviderIconVersion, activateProviderCatalog} from '../providerMetadata.js';
import {assert, equal} from './assert.js';

const root = ARGV[0], archive = Gio.File.new_for_path(`${root}/release.tgz`).load_contents(null)[1];
const hash = GLib.compute_checksum_for_bytes(GLib.ChecksumType.SHA256, new GLib.Bytes(archive));
let payload = archive;
let timestamp = 100000, version = '999.0.0', digest = hash, calls = 0;
const fetch = async url => {
    calls++;
    if (!url.endsWith('/latest')) return payload;
    return new TextEncoder().encode(JSON.stringify({tag_name: `v${version}`, assets: [{
        name: `agenticdriver-provider-icons-${version}.tgz`, digest: `sha256:${digest}`,
        browser_download_url: `https://github.com/agenticdriver/provider-icons/releases/download/v${version}/agenticdriver-provider-icons-${version}.tgz`}]}));
};
const updater = new ProviderIconUpdater({root: `${root}/cache`, automatic: false, fetch, clock: () => timestamp});
updater.start();
let releaseFetch;
const ready = new Promise(resolve => { releaseFetch = resolve; });
const originalFetch = updater.fetch;
updater.fetch = async (...args) => { await ready; return originalFetch(...args); };
const inFlight = updater.update();
assert(updater.update() === inFlight, 'Concurrent callers must share the operation');
const competitor = new ProviderIconUpdater({root: `${root}/cache`, automatic: false,
    fetch: async () => { throw new Error('A competing window must not download'); }, clock: () => timestamp});
competitor.start();
await competitor.update();
assert(competitor.status.message.includes('Another window'));
competitor.stop();
releaseFetch();
await inFlight;
updater.fetch = originalFetch;
equal(updater.status.error, null);
equal(providerIconVersion, '999.0.0');
equal(resolveProviderIcon('Future Model').id, 'future');
assert(Gio.File.new_for_path(`${GLib.get_user_data_dir()}/fonts/UsageStatProviderIcons.ttf`).query_exists(null), 'Native font must be installed with the catalog');
assert(!Gio.File.new_for_path(`${root}/cache/999.0.0-${hash}/index.js`).query_exists(null));
const before = calls;
await updater.update(false);
equal(calls, before, 'Daily interval must survive a manual update');
timestamp += 86401;
await updater.update(false);
equal(calls, before + 1, 'Next day checks current release without downloading it again');
version = '999.0.1'; digest = '0'.repeat(64);
await updater.update();
assert(updater.status.error.includes('checksum'));
equal(providerIconVersion, '999.0.0', 'Failed update must preserve active icons');
payload = Gio.File.new_for_path(`${root}/invalid-catalog.tgz`).load_contents(null)[1];
digest = GLib.compute_checksum_for_bytes(GLib.ChecksumType.SHA256, new GLib.Bytes(payload));
await updater.update();
assert(updater.status.error.includes('metadata'));
equal(providerIconVersion, '999.0.0', 'An unusable catalog must preserve the last good generation');
const pointer = JSON.parse(new TextDecoder().decode(Gio.File.new_for_path(`${root}/cache/active.json`).load_contents(null)[1]));
equal(pointer.version, '999.0.0', 'Catalog validation must happen before activation');
payload = Gio.File.new_for_path(`${root}/invalid-svg.tgz`).load_contents(null)[1];
digest = GLib.compute_checksum_for_bytes(GLib.ChecksumType.SHA256, new GLib.Bytes(payload));
await updater.update();
assert(updater.status.error.includes('Invalid provider icon SVG'));
equal(providerIconVersion, '999.0.0', 'Malformed SVG must not replace the last working icons');
updater.stop();
activateProviderCatalog();
const restarted = new ProviderIconUpdater({root: `${root}/cache`, automatic: false, fetch, clock: () => timestamp});
restarted.start();
equal(providerIconVersion, '999.0.0', 'Cached generation must load without a download');
const manifest = Gio.File.new_for_path(`${root}/cache/999.0.0-${hash}/manifest.json`);
manifest.replace_contents(new TextEncoder().encode('{}'), null, false, Gio.FileCreateFlags.REPLACE_DESTINATION, null);
restarted.reload();
equal(providerIconVersion, bundledProviderIconVersion, 'Corrupt cache must restore bundled icons');
restarted.stop();
Gio.File.new_for_path(`${root}/cache/999.0.0-${hash}/fonts/UsageStatProviderIcons.ttf`).delete(null);
assert(Gio.File.new_for_path(`${GLib.get_user_data_dir()}/fonts/UsageStatProviderIcons.ttf`).query_exists(null),
    'Clearing the disposable icon cache must not remove the installed font');
const blockedPath = `${root}/not-a-directory`;
Gio.File.new_for_path(blockedPath).replace_contents(new Uint8Array([1]), null, false, Gio.FileCreateFlags.NONE, null);
const blocked = new ProviderIconUpdater({root: blockedPath, automatic: false, fetch});
blocked.start();
await blocked.update();
assert(blocked.status.error, 'Cache failures must be reported without stopping the host');
blocked.stop();
print('Passed: independent data update, no remote JS, daily scheduling, rollback, restart and corrupt-cache fallback');
